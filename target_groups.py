def get_core_groups() -> list:
    """Get only CORE groups (your personal groups)"""
    return CORE_GROUPS

def get_marketing_groups() -> list:
    """Get only MARKETING groups (all other groups)"""
    return MARKETING_GROUPS

def get_groups_by_category(category: str) -> list:
    """Get all groups in a specific category"""
    return GROUP_CATEGORIES.get(category, [])

def get_all_groups() -> list:
    """Get ALL target groups (core + marketing)"""
    return TARGET_GROUPS

def get_groups_for_testing() -> list:
    """Get a small subset of groups for testing (from core)"""
    return CORE_GROUPS[:5]

def get_group_count() -> int:
    """Get total number of groups"""
    return len(TARGET_GROUPS)

def print_group_summary():
    """Print a summary of all groups by category"""
    print("\n" + "=" * 60)
    print("📊 GROUP SUMMARY")
    print("=" * 60)
    print(f"📦 Total Groups: {len(TARGET_GROUPS)}")
    print(f"⭐ Core Groups: {len(CORE_GROUPS)}")
    print(f"📈 Marketing Groups: {len(MARKETING_GROUPS)}")
    print("\nBy Category:")
    for category, groups in GROUP_CATEGORIES.items():
        count = len(groups)
        star = "⭐" if category == "core" else "📌"
        print(f"  {star} {category.upper()}: {count} groups")
        for g in groups[:5]:
            print(f"    - {g}")
        if count > 5:
            print(f"    ... and {count - 5} more")
    print("=" * 60)

def search_groups(keyword: str) -> list:
    """Search for groups containing a keyword across ALL groups"""
    keyword_lower = keyword.lower()
    results = []
    for group in TARGET_GROUPS:
        if keyword_lower in group.lower():
            results.append(group)
    return results

def search_core_groups(keyword: str) -> list:
    """Search only CORE groups for a keyword"""
    keyword_lower = keyword.lower()
    results = []
    for group in CORE_GROUPS:
        if keyword_lower in group.lower():
            results.append(group)
    return results

def get_unique_categories() -> list:
    """Get all unique category names"""
    return list(GROUP_CATEGORIES.keys())

